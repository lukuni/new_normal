def seed(db: Session) -> bool:
    if db.execute(select(Proposal.id).limit(1)).first():
        return False
    cons = []
    base = datetime(2026, 9, 20, 1, 0, tzinfo=timezone.utc)
    for title, summary, ref, org in CONSULTATIONS:
        c = Consultation(title=title, summary=summary, law_reference=ref, organizer=org,
                         created_at=base - timedelta(days=3), closes_at=base + timedelta(days=60))
        db.add(c)
        cons.append(c)
    db.flush()
    clf = get_classifier()
    t = base
    for ci, age, loc, text in PROPOSALS:
        text = scrub_pii(text)
        r = clf.classify(text)
        t += timedelta(hours=7 + len(text) % 11)
        p = Proposal(consultation_id=cons[ci].id if ci is not None else None, text=text, age_group=age,
                     location=loc, category=r.category, sentiment=r.sentiment, urgency=r.urgency,
                     confidence=r.confidence, classifier=r.classifier, content_hash=sha256(text), created_at=t)
        db.add(p)
        db.flush()
        append_block(db, p, at=t)
        db.flush()
    db.commit()
    return True
